    if len(country) != 2 or not country.isascii() or not country.isalpha():
        return False
    rule = country_rule(invoice_type)
    if rule == "gr":
        return country == "GR"
    if rule == "eu":
        return country in EU_COUNTRIES
    if rule == "third":
        return country != "GR" and country not in EU_COUNTRIES
    return True


